# -*- coding: utf-8 -*-
"""从 GMR 自带的 Xsens IK 表生成 SlimeVR 专用表。

为什么要另做一张表：
    GMR 原表（xsens_mvn_to_g1.json）对四肢的**朝向**给了很高的权重（肩 100、肘 10），
    这些权重是按 Xsens 骨骼的局部坐标约定调的。SlimeVR/VMC 走的是 Unity 人形骨骼，
    局部轴约定不同，直接套会把胳膊拧成"小臂前伸 90°"。

    动捕给的位置是**约定无关**的，所以这里的做法是：
      - 骨盆：位置+朝向都锁（朝向权重 100，决定整机朝向）
      - 躯干：朝向权重 20（防止上身乱转）
      - 四肢：**只给位置权重**，朝向权重 0 → 纯位置 IK

用法：
    python tools/make_ik_config.py            # 写到 configs/ik/slimevr_pos_to_g1.json
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from mocap_live.paths import DEVKIT_ROOT  # noqa: E402

SRC = DEVKIT_ROOT / "05_retarget/GMR/general_motion_retargeting/ik_configs/xsens_mvn_to_g1.json"
OUT = Path(__file__).resolve().parent.parent / "configs" / "ik" / "slimevr_pos_to_g1.json"

ROOT_ROT = 100          # 骨盆朝向：必须锁死，否则整机会乱转
TORSO_ROT = 20          # 躯干朝向：给一点，防止上身相对于腿乱扭
LIMB_ROT = 0            # 四肢朝向：0 = 纯位置 IK


def build(src: Path = SRC) -> dict:
    cfg = json.loads(src.read_text(encoding="utf-8"))
    for table in ("ik_match_table1", "ik_match_table2"):
        for frame, entry in cfg[table].items():
            # entry: [human_body, pos_weight, rot_weight, pos_offset, rot_offset]
            if frame == "pelvis":
                entry[2] = ROOT_ROT
            elif frame == "torso_link":
                entry[2] = TORSO_ROT
            else:
                entry[2] = LIMB_ROT
            # GMR 会跳过 (pos=0, rot=0) 的条目，并且不再给它建偏移表 ——
            # 原表里腿在 stage1 是"只有朝向(0,10)"，把朝向清零后必须补上位置权重
            if entry[1] == 0 and entry[2] == 0:
                entry[1] = 10
    cfg["_note"] = ("SlimeVR/VMC IK: limbs position-only, pelvis orientation locked. "
                    "Generated by tools/make_ik_config.py. "
                    "MUST stay pure ASCII - GMR opens this file with open() and no encoding, "
                    "so any non-ASCII byte crashes under a GBK Windows locale.")
    return cfg


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    cfg = build()
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    # 关键：必须 ensure_ascii=True。GMR 用 open() 读这个文件且不指定编码，
    # 在中文 Windows 上默认按 GBK 解码，一旦有 UTF-8 中文就抛 UnicodeDecodeError。
    out.write_text(json.dumps(cfg, indent=2, ensure_ascii=True), encoding="utf-8")
    text = out.read_text(encoding="utf-8")
    assert text.isascii(), "IK 表里混进了非 ASCII 字符，会在 GBK 环境下崩溃"
    print(f"已生成 {out}（纯 ASCII，GBK 环境安全）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
